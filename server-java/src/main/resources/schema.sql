-- 排班申请（医生提交->管理员审核）：审核通过后落盘为 schedules 行，C 端即可见。
-- schedule_id 审核通过时回填，关联生成的排班行；同医生同日同时段禁止重复提交（已有活跃排班或 PENDING 申请均拒绝）。
-- 必须在 staff_users 之后创建（submitted_by/reviewed_by 外键引用 staff_users）。
CREATE TABLE IF NOT EXISTS schedule_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(id),
    schedule_date DATE NOT NULL,
    time_slot VARCHAR(30) NOT NULL,
    total_slots INT NOT NULL,
    action VARCHAR(20) NOT NULL DEFAULT 'CREATE',
    target_schedule_id BIGINT REFERENCES schedules(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    submitted_by BIGINT NOT NULL REFERENCES staff_users(id),
    reviewed_by BIGINT REFERENCES staff_users(id),
    review_reason VARCHAR(500),
    schedule_id BIGINT REFERENCES schedules(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    CONSTRAINT ck_schedule_requests_total_slots_positive CHECK (total_slots > 0),
    CONSTRAINT ck_schedule_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_schedule_requests_action CHECK (action IN ('CREATE', 'MODIFY', 'DISABLE', 'ENABLE'))
);
CREATE INDEX IF NOT EXISTS idx_schedule_requests_doctor ON schedule_requests(doctor_id);
CREATE INDEX IF NOT EXISTS idx_schedule_requests_status ON schedule_requests(status);

