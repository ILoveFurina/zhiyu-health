-- 判重唯一性只约束有效挂号：已取消（CANCELLED）不占用 (profile, schedule) 唯一位，
-- 允许患者取消后重新挂同一排班。PG 表级 UNIQUE 不支持 WHERE，用部分唯一索引实现；
-- 幂等：先 DROP 旧表级约束（曾名为 uq_appointments_profile_schedule），再建索引。
ALTER TABLE appointments DROP CONSTRAINT IF EXISTS uq_appointments_profile_schedule;
CREATE UNIQUE INDEX IF NOT EXISTS uq_appointments_profile_schedule_active
    ON appointments (health_profile_id, schedule_id) WHERE status <> 'CANCELLED';

