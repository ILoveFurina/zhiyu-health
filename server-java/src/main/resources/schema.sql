-- Agent 调用日志（票 24）：每条工具进度事件一行，tool_start/tool_end 用 tool_call_id 配对。
-- 字段为白名单，**无任何原文列**（不存工具参数与返回体，硬约束 5：trace 不记录患者敏感原文）。
-- 不存在的列无法被误写，运行时无需脱敏逻辑（ADR-0018）。error_code 只存契约白名单码，
-- 非白名单统一记 TOOL_ERROR_UNKNOWN（复用 vision-errors.json 同款纪律）。
CREATE TABLE IF NOT EXISTS agent_call_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT NOT NULL REFERENCES chat_rounds(id) ON DELETE CASCADE,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    -- LangGraph 工具调用 ID：作为 tool_start/tool_end 配对键透传
    tool_call_id VARCHAR(64),
    tool_name VARCHAR(50) NOT NULL,
    -- 阶段：tool_start / tool_end
    phase VARCHAR(20) NOT NULL,
    -- tool_end 结果枚举：success/error/skipped；tool_start 时为 NULL
    result VARCHAR(20),
    -- duration_ms 由 server-java 按 tool_start->tool_end 墙钟计算（server-py 不背时钟）
    duration_ms INT,
    -- 只存契约白名单码；非白名单统一记 TOOL_ERROR_UNKNOWN
    error_code VARCHAR(50),
    -- 脱敏后的工具响应摘要（server-py 对返回体遮蔽敏感原文后截断，仅 tool_end 有值）。
    -- 无患者敏感原文（硬约束 5），仅供 B 端 trace 展示用，非契约白名单字段。
    tool_output_summary TEXT,
    -- 同一轮内的事件序号，B 端按 round_id + seq 还原顺序
    seq INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_agent_call_logs_phase CHECK (phase IN ('tool_start', 'tool_end')),
    CONSTRAINT ck_agent_call_logs_result CHECK (result IS NULL OR result IN ('success', 'error', 'skipped'))
);

