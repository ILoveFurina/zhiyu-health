-- 智愈业务库 schema（PostgreSQL 16），镜像既有 Python 模型，勿改列名语义
-- 主键用 BY DEFAULT IDENTITY，保证幂等 seed 可写显式 id
-- 开发期 schema 演进约定：drop + recreate + seed，不做隐式迁移

-- pgvector 扩展：knowledge_chunks 向量检索依赖（云库 init.sql 已装，此处兜底防裸库）
CREATE EXTENSION IF NOT EXISTS vector;

-- 医院只承载名称与等级（票 49）：地址/坐标/就诊指引静态值全部下沉到院区，
-- 医院不再承载院区地址语义，全链外键限制删除、禁止级联删除（ADR-0027）。
CREATE TABLE IF NOT EXISTS hospitals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    level VARCHAR(30)
);

-- 院区：同一家医院下具有独立地址与坐标的就诊地点（票 49，ADR-0027）。
-- 服务城市由院区 city_code/city_name 动态聚合，任何查询不得写死城市。
CREATE TABLE IF NOT EXISTS hospital_campuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    name VARCHAR(100) NOT NULL,
    city_code VARCHAR(20) NOT NULL,
    city_name VARCHAR(50) NOT NULL,
    address VARCHAR(255) NOT NULL,
    longitude DOUBLE PRECISION,
    latitude DOUBLE PRECISION,
    -- 就诊指引卡静态来源（票 43 迁至院区）：地址错误后果重，演示用虚构静态值，非 LLM 生成
    floor VARCHAR(30),
    materials TEXT,
    precautions TEXT,
    CONSTRAINT uq_hospital_campuses_hospital_name UNIQUE (hospital_id, name)
);

-- 平台标准科室目录（票 49）：跨医院科室导航，按「科类 → 标准科室」组织。
-- 医院实际科室必须以非空外键映射到标准科室，跨医院号源查询只经该映射匹配，
-- 不依赖名称字符串相等。
CREATE TABLE IF NOT EXISTS standard_departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_standard_departments_category_name UNIQUE (category, name)
);

-- 院区科室分类：一个院区为组织和展示本院区科室而维护的分类及顺序；
-- 分类不是平台统一枚举，不参与 Agent 医学判断。
-- 开发期 drop + recreate：departments 先 DROP 解除对本表的引用，再重建本表（hospital_id->campus_id）。
DROP TABLE IF EXISTS departments CASCADE;
DROP TABLE IF EXISTS department_categories;

CREATE TABLE IF NOT EXISTS department_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id BIGINT NOT NULL REFERENCES hospital_campuses(id),
    name VARCHAR(50) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_department_categories_campus_name UNIQUE (campus_id, name)
);

-- 实际科室：归属具体院区，并归入所属院区的科室分类（票 49）。
-- category 必须与 campus 为同一院区（由 server-java service 校验，DB 不跨表约束）。
-- 幂等补列：旧库 departments 表若缺少 campus_id/category_id/standard_department_id
--（来自合并前 schema），CREATE TABLE IF NOT EXISTS 不会修改已存在的表。
-- 开发期按约定 drop + recreate + seed：先删旧表（CASCADE 移除 doctors FK 约束），
-- 再重建含新列的表，最后补回 doctors FK 约束。

CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus_id BIGINT NOT NULL REFERENCES hospital_campuses(id),
    category_id BIGINT NOT NULL REFERENCES department_categories(id),
    standard_department_id BIGINT NOT NULL REFERENCES standard_departments(id),
    name VARCHAR(100),
    floor VARCHAR(30),
    location VARCHAR(255)
);

-- doctors 表被 schedules/staff_users/consultation_records/prescriptions/prescription_templates
-- 五张表外键引用，DROP 会因依赖被拒；改用幂等 ALTER ADD COLUMN 补 gender/birth_date，
-- 不重建表，避免级联移除上述五表的 FK 约束（seed.sql 末尾仅补回 doctors->departments FK）。
CREATE TABLE IF NOT EXISTS doctors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(id),
    name VARCHAR(50),
    gender VARCHAR(10),
    birth_date DATE,
    title VARCHAR(50),
    registration_fee DECIMAL(10,2) NOT NULL DEFAULT 0,
    specialty TEXT,
    photo_url VARCHAR(500)
);
-- 旧库 doctors 若缺 gender/birth_date 列，幂等补上；新库 CREATE TABLE 已含，此句无害。
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS gender VARCHAR(10);
ALTER TABLE doctors ADD COLUMN IF NOT EXISTS birth_date DATE;

-- 补回 doctors.department_id→departments(id) FK 约束。
-- 当旧库 departments 被 CASCADE 删除后，doctors 表上的 FK 约束也被移除；
-- 而 CREATE TABLE IF NOT EXISTS doctors 不会修改已存在的表，故 FK 不会自动恢复。
-- 先删旧约束名（auto-generated: doctors_department_id_fkey）、再删本命名约束。
-- 注意：不能在此处就 ADD CONSTRAINT——DROP departments CASCADE 后 doctors 的旧行
-- （department_id=1..10）成了孤儿行，而重建后的 departments 此刻为空，立即加 FK 会因
-- 校验孤儿行而失败（启动报 fk_doctors_department 违规）。FK 必须等 seed.sql 重灌
-- departments/doctors 之后再补，见 seed.sql 末尾。
ALTER TABLE doctors DROP CONSTRAINT IF EXISTS doctors_department_id_fkey;
ALTER TABLE doctors DROP CONSTRAINT IF EXISTS fk_doctors_department;

