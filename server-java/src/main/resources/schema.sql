-- 健康观测（票 61，ADR-0031）：报告解读白名单项目由 server-java 确定性映射后沉淀。
-- 追加式来源模型：纠错不覆盖旧记录，而是旧记录 SUPERSEDED/current=FALSE + 追加 USER_CORRECTION 新记录；
-- REJECTED 保持 current=TRUE 以占用每日槽位、阻止重复上传复活。
CREATE TABLE IF NOT EXISTS health_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    health_profile_id BIGINT NOT NULL REFERENCES health_profiles(id),
    -- REPORT_AI 与 USER_CORRECTION 都必须关联来源报告，不允许无来源观测
    report_interpretation_id BIGINT NOT NULL REFERENCES report_interpretations(id),
    metric_code VARCHAR(32) NOT NULL,
    value_numeric NUMERIC(10, 2),
    value_category VARCHAR(32),
    -- 规范单位（契约 canonical_unit）；数值观测必有单位，分类观测无单位
    unit VARCHAR(32),
    reference_range VARCHAR(100),
    observed_on DATE NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    verification_status VARCHAR(32) NOT NULL,
    current BOOLEAN NOT NULL DEFAULT TRUE,
    supersedes_id BIGINT REFERENCES health_observations(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_health_observations_value
        CHECK ((value_numeric IS NOT NULL AND value_category IS NULL)
            OR (value_numeric IS NULL AND value_category IS NOT NULL)),
    CONSTRAINT ck_health_observations_metric
        CHECK (metric_code IN ('HEIGHT', 'WEIGHT', 'BMI', 'SYSTOLIC_BP', 'DIASTOLIC_BP',
                               'FASTING_GLUCOSE', 'TOTAL_CHOLESTEROL',
                               'ABO_BLOOD_TYPE', 'RH_D_BLOOD_TYPE')),
    CONSTRAINT ck_health_observations_metric_value_type
        CHECK ((metric_code IN ('ABO_BLOOD_TYPE', 'RH_D_BLOOD_TYPE')
                    AND value_category IS NOT NULL AND value_numeric IS NULL AND unit IS NULL)
            OR (metric_code NOT IN ('ABO_BLOOD_TYPE', 'RH_D_BLOOD_TYPE')
                    AND value_numeric IS NOT NULL AND value_category IS NULL AND unit IS NOT NULL)),
    CONSTRAINT ck_health_observations_category
        CHECK (value_category IS NULL
            OR value_category IN ('A', 'B', 'AB', 'O', 'POSITIVE', 'NEGATIVE')),
    CONSTRAINT ck_health_observations_source
        CHECK (source_type IN ('REPORT_AI', 'USER_CORRECTION')),
    CONSTRAINT ck_health_observations_status
        CHECK (verification_status IN ('UNVERIFIED', 'USER_CONFIRMED', 'REJECTED', 'SUPERSEDED'))
);

-- 同报告映射幂等：重复回调/重试不得重复生成观测
CREATE UNIQUE INDEX IF NOT EXISTS uq_health_observations_report_metric
    ON health_observations(report_interpretation_id, metric_code) WHERE source_type = 'REPORT_AI';

-- 每日当前槽位唯一：同一档案同一指标同一天最多一个 current 值，历史版本以 current=FALSE 保留
CREATE UNIQUE INDEX IF NOT EXISTS uq_health_observations_current_slot
    ON health_observations(health_profile_id, metric_code, observed_on) WHERE current = TRUE;

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL,
    -- 须容纳契约 message_kinds 最长值（hospital_recommendations=24）并留余量；
    -- 票 33：VARCHAR(20) 溢出曾使卡片落库失败并掐断 SSE 中继，列宽由 ContractsConsistencyTest 钉死
    kind VARCHAR(32) NOT NULL DEFAULT 'text',
    content TEXT NOT NULL,
    effort VARCHAR(10),
    -- 票 44：C 端 Agent 回复的情绪标注（calm/anxious/fearful），由 server-py 串行二次
    -- LLM 调用产生挂 message 事件，server-java 透传落库供历史回看复现情绪色；用户消息为 NULL。
    -- VARCHAR(16) 容纳枚举最长值 fearful(7) 并留余量；CHECK 限定取值，防脏值写入。
    emotion VARCHAR(16),
    report_interpretation_id BIGINT REFERENCES report_interpretations(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_messages_emotion CHECK (emotion IS NULL OR emotion IN ('calm', 'anxious', 'fearful')),
    -- 票 50：kind 取值收敛为契约 message_kinds + red_flag（规则引擎本地产物，不在契约清单内），
    -- 防脏 kind 写入；取值清单与契约的一致性由 ContractsConsistencyTest 钉死
    CONSTRAINT ck_messages_kind CHECK (kind IN (
        'text', 'doctor_recommendations', 'doctor_slots', 'hospital_recommendations',
        'appointment', 'appointments', 'report_upload', 'report_interpretation',
        'report_context', 'skin_analysis', 'image', 'diet_analysis', 'tongue_analysis',
        'department_slots', 'department_options', 'red_flag'))
);

-- messages.kind CHECK 幂等重建：CREATE TABLE IF NOT EXISTS 对旧库不会补建约束，
-- 与 ck_messages_emotion 同一套路——新建库先 DROP 再 ADD 结果一致，旧库 DROP no-op + ADD 建上；
-- 票 50 新增 department_slots、票 65 新增 department_options 时旧库约束同步扩列。
ALTER TABLE messages DROP CONSTRAINT IF EXISTS ck_messages_kind;
ALTER TABLE messages
    ADD CONSTRAINT ck_messages_kind CHECK (kind IN (
        'text', 'doctor_recommendations', 'doctor_slots', 'hospital_recommendations',
        'appointment', 'appointments', 'report_upload', 'report_interpretation',
        'report_context', 'skin_analysis', 'image', 'diet_analysis', 'tongue_analysis',
        'department_slots', 'department_options', 'red_flag'));

-- messages.emotion 列幂等补齐：CREATE TABLE IF NOT EXISTS 对已存在的表不会 ADD COLUMN，
-- 云库若停留在票 44 之前的版本会缺该列，导致后续 COMMENT ON COLUMN 引用失败并阻断启动。
-- ADD COLUMN IF NOT EXISTS 命中“列已存在”即整条 no-op，新建库与旧库均可重复执行。
-- 注意：仅 ADD COLUMN 时不带 CONSTRAINT 子句--当列已存在时整条被跳过、约束也不会补建，
-- 旧库会缺 ck_messages_emotion。故约束用 DROP IF EXISTS + ADD 幂等重建：
-- 新建库（CREATE TABLE 已建约束）先 DROP 再 ADD，结果一致；旧库则 DROP no-op + ADD 建上。
-- 不使用 DO $$ 块：Spring ScriptUtils 默认按 ';' 切分语句、不识别 dollar quote，
-- 会把块内分号误判为语句结束符导致 Unterminated dollar quote。
ALTER TABLE messages ADD COLUMN IF NOT EXISTS emotion VARCHAR(16);
ALTER TABLE messages DROP CONSTRAINT IF EXISTS ck_messages_emotion;
ALTER TABLE messages
    ADD CONSTRAINT ck_messages_emotion
    CHECK (emotion IS NULL OR emotion IN ('calm', 'anxious', 'fearful'));

